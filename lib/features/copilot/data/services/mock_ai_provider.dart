import '../../domain/entities/chat_message.dart';
import '../../domain/entities/copilot_context.dart';
import '../../domain/services/ai_provider.dart';

/// Offline, rule-based stand-in for a real LLM. Produces helpful Persian
/// answers grounded in the rider's bike, streamed word-by-word to mimic a
/// live provider. Replaceable without touching the UI.
class MockAiProvider implements AiProvider {
  const MockAiProvider();

  @override
  String get displayName => 'موتو‌کوپایلت (نسخه آزمایشی)';

  @override
  bool get isLive => false;

  @override
  Stream<String> streamReply({
    required List<ChatMessage> history,
    required CopilotContext context,
  }) async* {
    final prompt = history.isNotEmpty ? history.last.content : '';
    final answer = _answer(prompt, context);

    // Stream word-by-word so the UI shows a natural typing effect.
    final words = answer.split(' ');
    for (var i = 0; i < words.length; i++) {
      await Future<void>.delayed(const Duration(milliseconds: 28));
      yield i == 0 ? words[i] : ' ${words[i]}';
    }
  }

  String _answer(String prompt, CopilotContext ctx) {
    final p = prompt.toLowerCase();
    final bike = ctx.hasBike ? ctx.bikeName! : 'موتورت';

    bool has(List<String> keys) => keys.any(p.contains);

    if (has(['روغن', 'اویل', 'oil'])) {
      final km = ctx.mileage != null ? ' (کیلومتر فعلی حدود ${ctx.mileage})' : '';
      return 'برای $bike$km معمولاً تعویض روغن هر ۱۵۰۰ تا ۲۰۰۰ کیلومتر '
          'توصیه می‌شود. از روغن با گرید مناسب آب‌وهوای گرم ایران مثل 10W40 '
          'استفاده کن و همزمان فیلتر روغن را هم بررسی کن. برای ثبت سرویس می‌تونی '
          'از بخش «یادآور سرویس» اپ استفاده کنی.';
    }
    if (has(['استارت', 'روشن نمی', 'روشن نمیشه', 'start'])) {
      return 'اگر $bike روشن نمی‌شود، اول این‌ها را چک کن: ۱) شارژ باتری و '
          'اتصالات، ۲) سوخت و شیر بنزین، ۳) فیوز و کلید استارت، ۴) شمع. '
          'اگر استارت می‌زند ولی روشن نمی‌شود معمولاً مشکل از جرقه یا سوخت‌رسانی '
          'است. برای عیب‌یابی مرحله‌به‌مرحله ابزار «موتوفیکس» را باز کن.';
    }
    if (has(['دود', 'smoke'])) {
      return 'رنگ دود مهم است: دود آبی نشانه سوختن روغن (مشکل رینگ/گژن‌پین یا '
          'سوپاپ)، دود سفید غلیظ نشانه ورود مایع خنک‌کننده یا میعان، و دود سیاه '
          'نشانه پرت بودن سوخت (کاربراتور/انژکتور) است. اگر دود آبی مداوم داری، '
          'برای جلوگیری از آسیب بیشتر بهتره موتور را زیاد نرونی و به تعمیرکار '
          'مراجعه کنی.';
    }
    if (has(['صدا', 'لرزش', 'noise'])) {
      return 'صدای غیرعادی را بر اساس محل تشخیص بده: تق‌تق از بالای موتور معمولاً '
          'تنظیم سوپاپ، صدای زنجیر از کشیدگی یا روغن‌کاری نشدن، و صدای فلزی از '
          'کلاچ یا یاتاقان می‌آید. اگر صدا با دور موتور زیاد می‌شود حتماً '
          'بررسی تخصصی لازم است.';
    }
    if (has(['ترمز', 'لنت', 'brake'])) {
      return 'لنت ترمز را هر ۸ تا ۱۰ هزار کیلومتر یا وقتی صدای جیر می‌دهد بررسی '
          'کن. اگر اهرم ترمز اسفنجی شده، احتمالاً هواگیری یا تعویض روغن ترمز '
          'لازم است. ایمنی ترمز را جدی بگیر.';
    }
    if (has(['زنجیر', 'chain'])) {
      return 'زنجیر را هر ۵۰۰ کیلومتر روغن‌کاری و لقی‌اش را تنظیم کن (حدود ۲ تا '
          '۳ سانت بازی عمودی مناسب است). زنجیر خشک یا شل باعث افت شتاب و خطر '
          'پریدن می‌شود.';
    }
    if (has(['باتری', 'battery'])) {
      return 'عمر معمول باتری موتور ۲ تا ۳ سال است. اگر استارت ضعیف شده یا چراغ‌ها '
          'کم‌نور است، ولتاژ باتری را اندازه بگیر (حدود ۱۲.۶ ولت در حالت خاموش). '
          'اتصالات را تمیز و سفت نگه دار.';
    }
    if (has(['بیمه', 'ثالث', 'insurance'])) {
      return 'بیمه شخص ثالث برای موتورسیکلت اجباری است. از بخش «موتوبیمه» اپ '
          'می‌تونی استعلام بگیری و آنلاین بخری. اگر موتورت ارزش بالایی دارد، '
          'بیمه بدنه و سرقت هم پوشش خوبی است.';
    }
    if (has(['قیمت', 'ارزش', 'بفروشم', 'price', 'value'])) {
      return 'برای برآورد قیمت $bike می‌تونی از ابزار «موتوسنج» استفاده کنی؛ '
          'با وارد کردن مدل، سال، کیلومتر و وضعیت بدنه یک بازه قیمت تقریبی '
          'می‌دهد. قیمت نهایی به سلامت فنی و مدارک هم بستگی دارد.';
    }
    if (has(['خرید', 'بخرم', 'پیشنهاد', 'buy', 'recommend'])) {
      return 'اگر دنبال انتخاب موتور مناسب هستی، ابزار «موتوتایپ» بر اساس بودجه، '
          'سبک رانندگی و کاربری روزانه چند گزینه پیشنهاد می‌دهد. برای خرید '
          'کارکرده هم حتماً راهنمای خرید و کارشناسی فنی و استعلام سند را ببین.';
    }
    if (has(['لاستیک', 'تایر', 'tire'])) {
      return 'لاستیک را از نظر عمق آج، ترک خوردگی و سن (تاریخ تولید روی دیواره) '
          'بررسی کن. لاستیک سفت‌شده حتی با آج خوب هم چسبندگی‌اش کم می‌شود و باید '
          'تعویض شود.';
    }
    if (has(['بنزین', 'مصرف', 'سوخت', 'fuel'])) {
      return 'افزایش ناگهانی مصرف سوخت معمولاً به فیلتر هوای کثیف، شمع فرسوده، '
          'باد کم لاستیک یا تنظیم نبودن سوخت‌رسانی برمی‌گردد. این موارد را به '
          'ترتیب چک کن.';
    }
    if (has(['سلام', 'درود', 'hi', 'hello'])) {
      return 'سلام! من موتو‌کوپایلت هستم 🏍️ هر سوالی درباره نگهداری، عیب‌یابی، '
          'بیمه یا خرید ${ctx.hasBike ? bike : 'موتورت'} داری بپرس.';
    }

    return 'سوال خوبیه! می‌تونم درباره نگهداری و سرویس، عیب‌یابی، بیمه، قیمت و '
        'خرید ${ctx.hasBike ? bike : 'موتور'} کمکت کنم. کمی دقیق‌تر بگو موضوع '
        'چیه تا بهترین راهنمایی رو بدم. (این پاسخ‌ها فعلاً از نسخه آزمایشی '
        'دستیار است و با اتصال به سرویس هوش مصنوعی دقیق‌تر می‌شود.)';
  }
}
